import { defineConfig, externalizeDepsPlugin } from 'electron-vite'
import react from '@vitejs/plugin-react'
import path from 'node:path'
import fs from 'node:fs'
import type { Plugin } from 'vite'

/**
 * The tab-view preload (out/preload/index.js) runs with sandbox:true, where
 * require() resolves ONLY `electron` — no relative chunks, no node builtins,
 * no node_modules. So there is exactly ONE preload entry and it must bundle
 * everything into that single file (single entry = no code splitting).
 *
 * The chrome UI window gets out/preload/ui.js, GENERATED from index.js by the
 * plugin below (runs on every build AND on every dev-watch rebuild, before
 * electron boots): identical bridge + the electron-chrome-extensions
 * browser-action glue, which is only legal because the chrome window runs
 * with sandbox:false. Tab views never load ui.js.
 */
function generateUiPreload(): Plugin {
  return {
    name: 'aether-generate-ui-preload',
    apply: 'build',
    writeBundle() {
      const indexJs = path.resolve(__dirname, 'out/preload/index.js')
      const uiJs = path.resolve(__dirname, 'out/preload/ui.js')
      if (!fs.existsSync(indexJs)) return
      const footer = `
/* ---- chrome-UI-only glue (generated by electron.vite.config.ts) ---- */
try {
  var __aetherChromeUI =
    location.protocol === 'file:' || ['localhost', '127.0.0.1'].indexOf(location.hostname) >= 0
  if (__aetherChromeUI) {
    require('electron-chrome-extensions/dist/browser-action').injectBrowserAction()
  }
} catch (err) {
  console.error('[extensions] browser-action injection failed:', err)
}
`
      fs.writeFileSync(uiJs, fs.readFileSync(indexJs, 'utf8') + footer)
    }
  }
}

/**
 * Sandboxed plain preloads (v2.7.0 farbling, v2.8.0 gestures) — plain JS,
 * NOT bundled (they must run import-free inside sandboxed frames). Copied
 * verbatim from src/preload/*.js to out/preload/ on every build / dev-watch
 * rebuild, the same trigger window the ui.js generator uses.
 */
function copyFarblePreload(): Plugin {
  return {
    name: 'aether-copy-farble-preload',
    apply: 'build',
    writeBundle() {
      // shipped sandbox-safe plain preloads:
      //   src/preload/farble.js   → out/preload/farble.js
      //   src/preload/gesture.js  → out/preload/gesture.js
      const names = ['farble.js', 'gesture.js']
      for (const name of names) {
        const src = path.resolve(__dirname, 'src/preload', name)
        const dst = path.resolve(__dirname, 'out/preload', name)
        try {
          fs.mkdirSync(path.dirname(dst), { recursive: true })
          fs.copyFileSync(src, dst)
        } catch (err) {
          console.error(`[preload] ${name} copy failed:`, err)
        }
      }
    }
  }
}

export default defineConfig({
  main: {
    plugins: [externalizeDepsPlugin()]
  },
  preload: {
    // sandboxed tab views can only require("electron") — keep the bundle lean
    // and verify it after every build with scripts/patch-preload-sandbox.cjs
    plugins: [externalizeDepsPlugin(), generateUiPreload(), copyFarblePreload()]
  },
  renderer: {
    plugins: [react()]
  }
})